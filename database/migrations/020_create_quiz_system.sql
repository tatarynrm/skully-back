-- Quiz System: categories, questions, user answers, stats, daily sessions

CREATE TABLE IF NOT EXISTS quiz_categories (
  id SERIAL PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  emoji VARCHAR(10) NOT NULL
);

CREATE TABLE IF NOT EXISTS quiz_questions (
  id SERIAL PRIMARY KEY,
  category_id INT NOT NULL REFERENCES quiz_categories(id),
  question_text TEXT NOT NULL,
  option_a VARCHAR(300) NOT NULL,
  option_b VARCHAR(300) NOT NULL,
  option_c VARCHAR(300) NOT NULL,
  option_d VARCHAR(300) NOT NULL,
  correct_option CHAR(1) NOT NULL CHECK (correct_option IN ('A','B','C','D')),
  difficulty VARCHAR(10) NOT NULL DEFAULT 'medium' CHECK (difficulty IN ('easy','medium','hard'))
);

CREATE TABLE IF NOT EXISTS quiz_user_answers (
  id SERIAL PRIMARY KEY,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  question_id INT NOT NULL REFERENCES quiz_questions(id),
  is_correct BOOLEAN NOT NULL,
  answered_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(user_id, question_id)
);

CREATE TABLE IF NOT EXISTS quiz_user_stats (
  user_id INT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  total_points INT NOT NULL DEFAULT 0,
  correct_answers INT NOT NULL DEFAULT 0,
  sessions_completed INT NOT NULL DEFAULT 0,
  premium_days_earned INT NOT NULL DEFAULT 0,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS quiz_daily_sessions (
  id SERIAL PRIMARY KEY,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  session_date DATE NOT NULL,
  question1_id INT REFERENCES quiz_questions(id),
  question2_id INT REFERENCES quiz_questions(id),
  category_id INT REFERENCES quiz_categories(id),
  both_correct BOOLEAN DEFAULT FALSE,
  total_time_seconds INT,
  premium_awarded BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(user_id, session_date)
);

CREATE INDEX IF NOT EXISTS idx_quiz_user_answers_user ON quiz_user_answers(user_id);
CREATE INDEX IF NOT EXISTS idx_quiz_daily_sessions_user ON quiz_daily_sessions(user_id, session_date);

